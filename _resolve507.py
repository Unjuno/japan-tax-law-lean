import json, re, subprocess
from pathlib import Path

PAT = re.compile(r"^<<<<<<< HEAD[^\n]*\n(.*?)^=======[^\n]*\n(.*?)^>>>>>>>[^\n]*\n?", re.S | re.M)

def split_sides(text):
    def clean(s):
        return "<<<<<<<" not in s and "=======" not in s and ">>>>>>>" not in s
    ours = PAT.sub(lambda m: m.group(1), text)
    theirs = PAT.sub(lambda m: m.group(2), text)
    assert clean(ours) and clean(theirs)
    return ours, theirs

# 1) JapanTaxLaw.lean - additive imports: union both sides.
p = Path("JapanTaxLaw.lean")
ours, theirs = split_sides(p.read_text(encoding="utf-8"))
base = [ln for ln in ours.splitlines()]
base_set = set(base)
extra = [ln for ln in theirs.splitlines() if ln.startswith("import ") and ln not in base_set]
last_imp = max(i for i, ln in enumerate(base) if ln.startswith("import "))
for j, ln in enumerate(extra):
    base.insert(last_imp + 1 + j, ln)
p.write_text("\n".join(base) + "\n", encoding="utf-8")
print("JapanTaxLaw.lean union; imports:", sum(1 for l in base if l.startswith("import ")))

