#!/usr/bin/env python3
"""Reviewable name->law-ID candidate layer for unbound reference names (Objective §2).

Read-only evidence layer. For each UNRESOLVED reference name recorded by
recursive_discovery, attempt CONSERVATIVE matching against the full e-Gov law
list (9001 entries): exact normalized name, or base-name after stripping a
施行令/施行規則/施行規程 suffix. Only high-precision structural matches are
recorded, and EVERY candidate carries status UNVERIFIED_REVIEW_REQUIRED — this
script NEVER auto-binds a reference and NEVER weakens rules.py's family-only
classifier. It produces review material only (H/T/D/C/U recorded per candidate).

Usage: python scripts/ci/bind_reference_names.py
"""
from __future__ import annotations
import json, re, sys, xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DISCOVERY = REPO / "data" / "RECURSIVE_DISCOVERY_RESOLVED.json"
LAWLIST = REPO / "scripts" / "law_audit" / "inventory" / "lawlists_1.xml"
OUT = REPO / "data" / "REFERENCE_NAME_BINDINGS.json"
OUT_MD = REPO / "docs" / "REFERENCE_NAME_BINDINGS.md"

SUFFIX = ("施行令", "施行規則", "施行規程", "施行細則")


def norm(s: str) -> str:
    return re.sub(r"[\s\u3000]+", "", str(s)).strip()


def base(name: str) -> str:
    s = norm(name)
    for suf in SUFFIX:
        if s.endswith(suf) and len(s) > len(suf):
            return s[:-len(suf)]
    return s


def load_lawlist() -> dict[str, list[str]]:
    """Return {normalized_law_name: [law_ids]} and a base-name index."""
    root = ET.parse(LAWLIST).getroot()
    exact: dict[str, list[str]] = {}
    for info in root.iter("LawNameListInfo"):
        lid = (info.findtext("LawId") or "").strip()
        name = (info.findtext("LawName") or "").strip()
        if lid and name:
            exact.setdefault(norm(name), []).append(lid)
    return exact


def main() -> int:
    exact = load_lawlist()
    base_index: dict[str, list[str]] = {}
    for name, ids in exact.items():
        base_index.setdefault(base(name), []).extend(ids)
    # dedupe
    for k in base_index:
        base_index[k] = sorted(set(base_index[k]))

    d = json.loads(DISCOVERY.read_text(encoding="utf-8"))
    unresolved = d.get("unresolved") or []

    candidates = []
    matched_exact = matched_base = 0
    for rec in unresolved:
        name = rec.get("name", "")
        n = norm(name)
        if not n:
            continue
        method = None
        ids: list[str] = []
        if n in exact:
            method, ids = "exact_law_name", exact[n]
            matched_exact += 1
        elif base(n) in base_index and base(n) != n:
            method, ids = "base_name_after_suffix_strip", base_index[base(n)]
            matched_base += 1
        if not ids:
            continue
        candidates.append({
            "reference_name": name,
            "occurrences": rec.get("occurrences", 0),
            "candidate_law_ids": ids[:10],
            "candidate_count": len(ids),
            "match_method": method,
            "status": "UNVERIFIED_REVIEW_REQUIRED",
            "H": "name maps to the listed law_id(s) by structural string match",
            "T": "re-run this script; compare against lawlists_1.xml SHA-256",
            "D": "UNVERIFIED - requires human confirmation, never auto-bound",
            "C": "a same/similar name may denote a historical or different law",
            "U": "high for homonyms; exact matches lower but still unverified",
        })
    candidates.sort(key=lambda x: (-x["occurrences"], x["reference_name"]))

    payload = {
        "tool": "scripts/ci/bind_reference_names.py",
        "claim": "review candidates only; not parsed, not modelled, not legally reviewed",
        "unresolved_names_total": len(unresolved),
        "candidates_recorded": len(candidates),
        "matched_exact": matched_exact,
        "matched_base_after_suffix_strip": matched_base,
        "lawlist_entries": len(exact),
        "candidates": candidates,
    }
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    lines = [
        "# Reviewable name -> law-ID candidates (Objective §2)",
        "",
        "Generated by `scripts/ci/bind_reference_names.py` from the pinned law list",
        "and recursive-discovery UNRESOLVED names. **Review material only.**",
        "Every candidate is `UNVERIFIED_REVIEW_REQUIRED`; nothing is auto-bound, and",
        "`rules.py`'s conservative family-only reference classifier is unchanged.",
        "",
        f"- unresolved names: {len(unresolved)}",
        f"- candidates recorded: {len(candidates)}",
        f"- exact-name matches: {matched_exact}",
        f"- base-name (suffix-stripped) matches: {matched_base}",
        "",
        "| reference name | occ | method | candidate law ids |",
        "|---|---|---|---|",
    ]
    for c in candidates[:80]:
        ids = ",".join(c["candidate_law_ids"][:3])
        lines.append(f"| {c['reference_name']} | {c['occurrences']} | {c['match_method']} | {ids} |")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"candidates {len(candidates)} / unresolved {len(unresolved)} "
          f"(exact {matched_exact}, base {matched_base})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
