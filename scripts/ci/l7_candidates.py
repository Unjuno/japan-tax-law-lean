#!/usr/bin/env python3
"""L7 per-candidate ledger — every audit candidate, with its review status.

Re-runs the pinned-law audit exactly as scripts/law_audit/inventory/sweep.py does
(same family cross-law wiring for act<->order<->rule) and writes one CSV row per
`candidate` finding. Every row carries review_status=unreviewed; NO legal review
has been performed. verified-anomaly candidates are written too (there are 0 today;
that is a measurement, not an absence-of-defect claim).

Output: docs/L7_CANDIDATES_UNREVIEWED.csv (committed; regenerated by CI gate).
Gate mode: fails if the committed CSV differs from regeneration.

This file is machine-authored: hand-editing it fails CI.
"""
import csv
import hashlib
import io
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from scripts.law_audit.model import load_law  # noqa: E402
from scripts.law_audit import rules  # noqa: E402

INVENTORY = REPO_ROOT / "data" / "INVENTORY.json"
OUT = REPO_ROOT / "docs" / "L7_CANDIDATES_UNREVIEWED.csv"

OVERLAY = REPO_ROOT / "data" / "HUMAN_REVIEWS.csv"
OVERLAY_HEADER = ["candidate_key", "review_status", "reviewer", "review_date", "source_citation"]


def candidate_key(row: list) -> str:
    """Stable identity of a candidate row, independent of generation order.

    rows are positional lists: [rule_id, severity, law_id, title, path, line,
    message, evidence, review_status, reviewer, review_date].
    """
    parts = [str(row[i]) for i in (0, 2, 4, 5, 6)]
    return hashlib.sha256("||".join(parts).encode("utf-8")).hexdigest()[:20]


def load_overlay() -> tuple[dict[str, dict], list[str]]:
    """Read sponsor-populated human review records; return (key -> row, errors).

    An absent or header-only overlay is valid and leaves every candidate
    unreviewed. Review records are NEVER fabricated by this script.
    """
    records: dict[str, dict] = {}
    errors: list[str] = []
    if not OVERLAY.exists():
        return records, errors
    with OVERLAY.open(encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames != OVERLAY_HEADER:
            errors.append(f"HUMAN_REVIEWS.csv header mismatch: {reader.fieldnames}")
            return records, errors
        for i, row in enumerate(reader, start=2):
            key = (row.get("candidate_key") or "").strip()
            reviewer = (row.get("reviewer") or "").strip()
            date = (row.get("review_date") or "").strip()
            status = (row.get("review_status") or "").strip()
            citation = (row.get("source_citation") or "").strip()
            if not key:
                errors.append(f"row {i}: missing candidate_key")
                continue
            if status not in ("reviewed", "confirmed-anomaly", "not-anomaly"):
                errors.append(f"row {i}: invalid review_status {status!r}")
                continue
            if not reviewer or not date:
                errors.append(f"row {i}: reviewer and review_date are mandatory")
                continue
            if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
                errors.append(f"row {i}: review_date must be YYYY-MM-DD")
                continue
            if not citation:
                errors.append(f"row {i}: source_citation is mandatory")
                continue
            if key in records:
                errors.append(f"row {i}: duplicate candidate_key {key}")
                continue
            records[key] = row
    return records, errors


HEADER = [
    "rule_id", "severity", "law_id", "official_title", "path", "line",
    "message", "evidence", "review_status", "reviewer", "review_date",
    "H", "T", "D", "C", "U",
]

# Objective §5: every detected candidate carries H (refutable hypothesis),
# T (reproduction test), D (mechanical decision), C (competing interpretation)
# and U (residual uncertainty). These are source-text finding records, NOT
# legal conclusions and NOT human reviews.
HT_HYPOTHESIS = {
    "PAREN.UNBALANCED": "The pinned article contains an unmatched full-width opening bracket at the recorded offset.",
    "REF.ITEM.MISSING": "A reference to an item number has no resolvable target item in the scanned scope.",
    "REF.ARTICLE.MISSING": "A reference to an article number has no matching article in the scanned scope.",
    "REF.PARA.MISSING": "A reference to a paragraph number has no matching paragraph in the enclosing or antecedent article.",
    "REF.SUPP.MISSING": "A reference to a supplementary-provision article has no matching article in any scanned SupplProvision.",
    "REF.ARTICLE.DELETED": "A reference names an article number absent from the pinned enforced version.",
    "REF.RELATIVE.MISSING": "A relative reference has no target in the declared scope.",
    "STRUCT.GAP.ARTICLE": "Integer article numbers are missing from the declared main scope.",
    "TOC.BODY.MISSING": "A table-of-contents chapter has no corresponding body chapter.",
}
HT_COMPETING = {
    "PAREN.UNBALANCED": "The bracket may be intentionally unclosed in the official text or an artifact of snapshot transcription.",
    "REF.ITEM.MISSING": "The target may be in another enforcement version, another law of the family, or an unscanned table structure.",
    "REF.ARTICLE.MISSING": "The target may be in another enforcement version, another law of the family, or a repealed provision.",
    "REF.PARA.MISSING": "The paragraph may be in a successor provision or an enforcement version not pinned here.",
    "REF.SUPP.MISSING": "The supplementary provision may belong to a different enforcement version or predecessor act.",
    "REF.ARTICLE.DELETED": "The deletion may be intentional and the reference may be a historical or cross-version pointer.",
    "REF.RELATIVE.MISSING": "The relative position may be computed in a different scope or a different version.",
    "STRUCT.GAP.ARTICLE": "Article numbering may be intentionally skipped by the legislature.",
    "TOC.BODY.MISSING": "The TOC may cover provisions in another scope or an unenforced version.",
}
HT_UNCERTAINTY = (
    "No human reviewer recorded; cross-version and cross-law scope not independently confirmed. "
    "D is mechanical reproducibility from the pinned snapshot only, not a legal conclusion."
)


def finding_identity(f) -> tuple:
    return (f.rule_id, norm(f.location), int(f.line) if str(f.line).isdigit() else 0,
            norm(f.message))


def htcdu(f, law_id, reproduced: bool) -> list[str]:
    rid = f.rule_id
    t = ("re-run rules.all_findings on the pinned snapshot; "
         f"rule_id={rid} law_id={law_id} location={norm(f.location)} line={f.line}; "
         "D=REPRODUCED iff the identity tuple appears in an independent second execution")
    return [
        HT_HYPOTHESIS.get(rid, "Unclassified structural finding; hypothesis pending classification."),
        t,
        "REPRODUCED" if reproduced else "NOT_REPRODUCED",
        HT_COMPETING.get(rid, "Alternative structural interpretation not yet classified."),
        HT_UNCERTAINTY,
    ]


def norm(text: str) -> str:
    if text is None:
        return ""
    s = str(text).replace("\r\n", "\n").replace("\r", "\n").replace("\n", " ⏎ ")
    return s.strip()


def collect_rows():
    inv = json.loads(INVENTORY.read_text(encoding="utf-8"))
    by_title: dict[str, dict] = {}
    for rec in inv["laws"]:
        t = rec.get("official_title")
        if t and t not in by_title:
            by_title[t] = rec

    def try_load_pinned_title(title: str):
        rec = by_title.get(title)
        if rec is None:
            return None
        snap = rec.get("raw_snapshot")
        if not snap:
            return None
        try:
            return load_law(REPO_ROOT / snap["source_file"])
        except Exception:
            return None

    def family_others(doc) -> dict:
        title = doc.law_title
        others: dict[str, object] = {}
        if title.endswith("施行規則"):
            parent = title[: -len("施行規則")]
            d_act = try_load_pinned_title(parent)
            d_ord = try_load_pinned_title(parent + "施行令")
            if d_act is not None:
                others["act"] = d_act
            if d_ord is not None:
                others["order"] = d_ord
            return others
        if title.endswith("施行令"):
            parent = title[: -len("施行令")]
            d_act = try_load_pinned_title(parent)
            d_rule = try_load_pinned_title(parent + "施行規則")
            if d_act is not None:
                others["act"] = d_act
            if d_rule is not None:
                others["rule"] = d_rule
            return others
        if rules._law_type_simple(doc.law_id) == "act":
            d_ord = try_load_pinned_title(title + "施行令")
            d_rule = try_load_pinned_title(title + "施行規則")
            if d_ord is not None:
                others["order"] = d_ord
            if d_rule is not None:
                others["rule"] = d_rule
        return others

    rows = []
    law_failures = 0
    for rec in inv["laws"]:
        lid = rec["law_id"]
        title = rec.get("official_title") or ""
        snap = rec.get("raw_snapshot")
        if not snap:
            continue
        try:
            doc = load_law(REPO_ROOT / snap["source_file"])
        except Exception:
            law_failures += 1
            continue
        others = family_others(doc)
        try:
            findings, _stats = rules.all_findings(doc, others)
            # Objective §5 reproduction test: an independent SECOND execution
            # from a freshly loaded pinned source. D is set from membership of
            # the identity tuple in that second scan.
            doc2 = load_law(REPO_ROOT / snap["source_file"])
            reproduced, _stats2 = rules.all_findings(doc2, family_others(doc2))
        except Exception:
            law_failures += 1
            continue
        second_ids = {finding_identity(f) for f in reproduced}
        for f in findings:
            rows.append([
                f.rule_id, f.severity, lid, norm(title), norm(f.location), f.line,
                norm(f.message), norm(getattr(f, "evidence", "")),
                "unreviewed", "", "",
                *htcdu(f, lid, finding_identity(f) in second_ids),
            ])
    return rows, law_failures


def render():
    rows, law_failures = collect_rows()
    rows.sort(key=lambda r: (r[0], r[2], r[4], int(r[5]) if str(r[5]).isdigit() else 0, r[6]))
    incomplete = [r for r in rows if any(not str(r[i]).strip() for i in (11, 12, 13, 14, 15))]
    if incomplete:
        print(f"FAIL: {len(incomplete)} candidate row(s) have an empty H/T/D/C/U field")
        raise SystemExit(1)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(HEADER)
    overlay, errors = load_overlay()
    if errors:
        for e in errors:
            print("FAIL HUMAN_REVIEWS.csv:", e)
        raise SystemExit(1)
    applied = 0
    for r in rows:
        rec = overlay.get(candidate_key(r))
        if rec:
            r[8] = rec["review_status"].strip()
            r[9] = rec["reviewer"].strip()
            r[10] = rec["review_date"].strip()
            applied += 1
        w.writerow(r)
    if overlay and applied != len(overlay):
        print(f"FAIL: {len(overlay) - applied} HUMAN_REVIEWS.csv key(s) did not match any candidate")
        raise SystemExit(1)
    return buf.getvalue(), len(rows), law_failures


def emit_review_template() -> int:
    """Write a sponsor-fillable CSV containing one stable key per candidate.

    The output goes to build/review_template.csv (git-ignored). Copy it to
    data/HUMAN_REVIEWS.csv and fill review_status / reviewer / review_date /
    source_citation. Blank records are NOT accepted by load_overlay, so an
    unfilled copy never creates a false review claim.
    """
    rows, law_failures = collect_rows()
    template = REPO_ROOT / "build" / "review_template.csv"
    template.parent.mkdir(parents=True, exist_ok=True)
    with template.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=OVERLAY_HEADER, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({
                "candidate_key": candidate_key(r),
                "review_status": "",
                "reviewer": "",
                "review_date": "",
                "source_citation": "",
            })
    print(f"wrote {template} ({len(rows)} candidate key(s), {law_failures} law failure(s))")
    print("Copy to data/HUMAN_REVIEWS.csv and fill only the rows you actually review.")
    return 0


def main():
    if sys.argv[1:] == ["--emit-review-template"]:
        return emit_review_template()
    out, n, law_failures = render()
    if sys.argv[1:] == ["--write"]:
        OUT.write_text(out, encoding="utf-8", newline="")
        print(f"wrote {OUT} ({n} candidate rows, {law_failures} law failure(s))")
        return 0
    if not OUT.exists():
        print(f"FAIL: {OUT} missing — run python scripts/ci/l7_candidates.py --write")
        return 1
    current = OUT.read_text(encoding="utf-8")
    if current != out:
        print(f"FAIL: {OUT} drifted — regenerate with 'python scripts/ci/l7_candidates.py --write' "
              f"(every candidate review-state row is machine-tracked; hand edits fail CI)")
        return 1
    print(f"L7 candidates ledger matches committed state ({n} rows; {law_failures} law failure(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
