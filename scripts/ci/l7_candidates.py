#!/usr/bin/env python3
"""L7 per-candidate ledger — every audit candidate, with its review status.

Re-runs the pinned-law audit exactly as scripts/law_audit/inventory/sweep.py does
(same family cross-law wiring for act<->order<->rule) and writes one CSV row per
`candidate` finding. Every row carries review_status=unreviewed; NO legal review
has been performed. verified-anomaly candidates are written too (there are 0 today;
that is a measurement, not an absence-of-defect claim).

Output: docs/L7_CANDIDATES_UNREVIEWED.csv (committed; regenerated by CI gate).
Gate mode: fails if the committed CSV differs from regeneration.

This file is machine-authored: hand-editing it fails CI.
"""
import csv
import hashlib
import io
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from scripts.law_audit.model import load_law  # noqa: E402
from scripts.law_audit import rules  # noqa: E402

INVENTORY = REPO_ROOT / "data" / "INVENTORY.json"
OUT = REPO_ROOT / "docs" / "L7_CANDIDATES_UNREVIEWED.csv"

OVERLAY = REPO_ROOT / "data" / "HUMAN_REVIEWS.csv"
OVERLAY_HEADER = ["candidate_key", "review_status", "reviewer", "review_date", "source_citation"]


def candidate_key(row: list) -> str:
    """Stable identity of a candidate row, independent of generation order.

    rows are positional lists: [rule_id, severity, law_id, title, path, line,
    message, evidence, review_status, reviewer, review_date].
    """
    parts = [str(row[i]) for i in (0, 2, 4, 5, 6)]
    return hashlib.sha256("||".join(parts).encode("utf-8")).hexdigest()[:20]


def load_overlay() -> tuple[dict[str, dict], list[str]]:
    """Read sponsor-populated human review records; return (key -> row, errors).

    An absent or header-only overlay is valid and leaves every candidate
    unreviewed. Review records are NEVER fabricated by this script.
    """
    records: dict[str, dict] = {}
    errors: list[str] = []
    if not OVERLAY.exists():
        return records, errors
    with OVERLAY.open(encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames != OVERLAY_HEADER:
            errors.append(f"HUMAN_REVIEWS.csv header mismatch: {reader.fieldnames}")
            return records, errors
        for i, row in enumerate(reader, start=2):
            key = (row.get("candidate_key") or "").strip()
            reviewer = (row.get("reviewer") or "").strip()
            date = (row.get("review_date") or "").strip()
            status = (row.get("review_status") or "").strip()
            citation = (row.get("source_citation") or "").strip()
            if not key:
                errors.append(f"row {i}: missing candidate_key")
                continue
            if status not in ("reviewed", "confirmed-anomaly", "not-anomaly"):
                errors.append(f"row {i}: invalid review_status {status!r}")
                continue
            if not reviewer or not date:
                errors.append(f"row {i}: reviewer and review_date are mandatory")
                continue
            if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
                errors.append(f"row {i}: review_date must be YYYY-MM-DD")
                continue
            if not citation:
                errors.append(f"row {i}: source_citation is mandatory")
                continue
            if key in records:
                errors.append(f"row {i}: duplicate candidate_key {key}")
                continue
            records[key] = row
    return records, errors


HEADER = [
    "rule_id", "severity", "law_id", "official_title", "path", "line",
    "message", "evidence", "review_status", "reviewer", "review_date",
]


def norm(text: str) -> str:
    if text is None:
        return ""
    s = str(text).replace("\r\n", "\n").replace("\r", "\n").replace("\n", " ⏎ ")
    return s.strip()


def collect_rows():
    inv = json.loads(INVENTORY.read_text(encoding="utf-8"))
    by_title: dict[str, dict] = {}
    for rec in inv["laws"]:
        t = rec.get("official_title")
        if t and t not in by_title:
            by_title[t] = rec

    def try_load_pinned_title(title: str):
        rec = by_title.get(title)
        if rec is None:
            return None
        snap = rec.get("raw_snapshot")
        if not snap:
            return None
        try:
            return load_law(REPO_ROOT / snap["source_file"])
        except Exception:
            return None

    def family_others(doc) -> dict:
        title = doc.law_title
        others: dict[str, object] = {}
        if title.endswith("施行規則"):
            parent = title[: -len("施行規則")]
            d_act = try_load_pinned_title(parent)
            d_ord = try_load_pinned_title(parent + "施行令")
            if d_act is not None:
                others["act"] = d_act
            if d_ord is not None:
                others["order"] = d_ord
            return others
        if title.endswith("施行令"):
            parent = title[: -len("施行令")]
            d_act = try_load_pinned_title(parent)
            d_rule = try_load_pinned_title(parent + "施行規則")
            if d_act is not None:
                others["act"] = d_act
            if d_rule is not None:
                others["rule"] = d_rule
            return others
        if rules._law_type_simple(doc.law_id) == "act":
            d_ord = try_load_pinned_title(title + "施行令")
            d_rule = try_load_pinned_title(title + "施行規則")
            if d_ord is not None:
                others["order"] = d_ord
            if d_rule is not None:
                others["rule"] = d_rule
        return others

    rows = []
    law_failures = 0
    for rec in inv["laws"]:
        lid = rec["law_id"]
        title = rec.get("official_title") or ""
        snap = rec.get("raw_snapshot")
        if not snap:
            continue
        try:
            doc = load_law(REPO_ROOT / snap["source_file"])
        except Exception:
            law_failures += 1
            continue
        others = family_others(doc)
        try:
            findings, _stats = rules.all_findings(doc, others)
        except Exception:
            law_failures += 1
            continue
        for f in findings:
            rows.append([
                f.rule_id, f.severity, lid, norm(title), norm(f.location), f.line,
                norm(f.message), norm(getattr(f, "evidence", "")),
                "unreviewed", "", "",
            ])
    return rows, law_failures


def render():
    rows, law_failures = collect_rows()
    rows.sort(key=lambda r: (r[0], r[2], r[4], int(r[5]) if str(r[5]).isdigit() else 0, r[6]))
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(HEADER)
    overlay, errors = load_overlay()
    if errors:
        for e in errors:
            print("FAIL HUMAN_REVIEWS.csv:", e)
        raise SystemExit(1)
    applied = 0
    for r in rows:
        rec = overlay.get(candidate_key(r))
        if rec:
            r[8] = rec["review_status"].strip()
            r[9] = rec["reviewer"].strip()
            r[10] = rec["review_date"].strip()
            applied += 1
        w.writerow(r)
    if overlay and applied != len(overlay):
        print(f"FAIL: {len(overlay) - applied} HUMAN_REVIEWS.csv key(s) did not match any candidate")
        raise SystemExit(1)
    return buf.getvalue(), len(rows), law_failures


def main():
    out, n, law_failures = render()
    if sys.argv[1:] == ["--write"]:
        OUT.write_text(out, encoding="utf-8", newline="")
        print(f"wrote {OUT} ({n} candidate rows, {law_failures} law failure(s))")
        return 0
    if not OUT.exists():
        print(f"FAIL: {OUT} missing — run python scripts/ci/l7_candidates.py --write")
        return 1
    current = OUT.read_text(encoding="utf-8")
    if current != out:
        print(f"FAIL: {OUT} drifted — regenerate with 'python scripts/ci/l7_candidates.py --write' "
              f"(every candidate review-state row is machine-tracked; hand edits fail CI)")
        return 1
    print(f"L7 candidates ledger matches committed state ({n} rows; {law_failures} law failure(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
