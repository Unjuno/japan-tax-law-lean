#!/usr/bin/env python3
"""Reviewable historical-revision pin candidate layer (Objective §2).

For every `historical_version_reference` recorded by recursive discovery
(names like 新租税特別措置法 / 旧法人税法), fetch the FULL revision history of
the resolved base law from the pinned e-Gov v2 endpoint and record a compact,
reviewable candidate ledger.

CRITICAL: this layer NEVER auto-pins a historical name to a revision. The
新/旧 distinction is a legal-context question and requires human review. Every
entry carries status PIN_REQUIRED_UNVERIFIED and H/T/D/C/U. It does NOT weaken
any gate and does NOT change the conservative family-only classifier in
rules.py.

Usage: python scripts/ci/pin_historical_revisions.py
"""
from __future__ import annotations
import hashlib, json, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts" / "law_audit" / "inventory"))
import build_inventory as bi  # noqa: E402

DISCOVERY = REPO / "data" / "RECURSIVE_DISCOVERY_RESOLVED.json"
OUT = REPO / "data" / "HISTORICAL_PIN_CANDIDATES.json"
OUT_MD = REPO / "docs" / "HISTORICAL_PIN_CANDIDATES.md"


def main() -> int:
    d = json.loads(DISCOVERY.read_text(encoding="utf-8"))
    refs = d.get("historical_version_references") or []
    base_ids = sorted({r.get("base_law_id") for r in refs if r.get("base_law_id")})

    histories: dict[str, dict] = {}
    for lid in base_ids:
        rec: dict = {"revisions": [], "fetch_status": "UNKNOWN", "revisions_sha256": ""}
        try:
            raw = bi.http_get_bytes(bi.REVISIONS_URL.format(law_id=lid))
            rec["revisions_sha256"] = hashlib.sha256(raw).hexdigest().upper()
            payload = json.loads(raw)
            for r in payload.get("revisions") or []:
                rec["revisions"].append({
                    "law_revision_id": str(r.get("law_revision_id") or ""),
                    "enforcement_date": str(r.get("amendment_enforcement_date") or ""),
                    "promulgate_date": str(r.get("amendment_promulgate_date") or ""),
                    "law_title": str(r.get("law_title") or ""),
                })
            rec["fetch_status"] = "OK" if rec["revisions"] else "NO_REVISIONS"
        except Exception as exc:  # noqa: BLE001 - network failure is a recorded status
            rec["fetch_status"] = "FETCH_FAILED"
            rec["note"] = str(exc)[:300]
        histories[lid] = rec
        print(f"{lid}: {rec['fetch_status']} revisions={len(rec['revisions'])}", flush=True)

    candidates = []
    for r in refs:
        lid = r.get("base_law_id")
        h = histories.get(lid, {})
        revs = h.get("revisions") or []
        candidates.append({
            "historical_name": r.get("name", ""),
            "occurrences": r.get("occurrences", 0),
            "base_law_id": lid,
            "base_name": r.get("base_name", ""),
            "base_resolution": r.get("base_resolution", ""),
            "requires_revision_pin": bool(r.get("requires_revision_pin")),
            "previously_pinned": bool(r.get("historical_revision_pinned")),
            "pin_status": "PIN_REQUIRED_UNVERIFIED",
            "fetch_status": h.get("fetch_status", "UNKNOWN"),
            "revisions_sha256": h.get("revisions_sha256", ""),
            "revision_count": len(revs),
            "candidate_revision_ids": [x["law_revision_id"] for x in revs],
            "H": "historical name denotes a specific enforced revision of the base law",
            "T": "re-run this script; compare revisions_sha256 against the e-Gov v2 response",
            "D": "UNVERIFIED - 新/旧 is a legal-context question; never mechanically pinned",
            "C": "新/旧 may denote a repeal/re-enactment, not merely a revision of this law_id",
            "U": "high - enforcement context and cross-statute reading required",
        })
    candidates.sort(key=lambda x: (-x["occurrences"], x["historical_name"]))

    payload = {
        "tool": "scripts/ci/pin_historical_revisions.py",
        "claim": "review candidates only; no revision is pinned, parsed, modelled or legally reviewed",
        "historical_names_total": len(refs),
        "base_law_ids_total": len(base_ids),
        "revisions_fetched_total": sum(len(h["revisions"]) for h in histories.values()),
        "pinned_total": 0,
        "candidates": candidates,
        "histories": histories,
    }
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    lines = [
        "# Reviewable historical-revision pin candidates (Objective §2)",
        "",
        "Generated by `scripts/ci/pin_historical_revisions.py` from the recursive-discovery",
        "historical references and the e-Gov v2 revision histories of their base laws.",
        "**No name is auto-pinned.** Every entry is `PIN_REQUIRED_UNVERIFIED`; the 新/旧",
        "distinction requires human legal review of enforcement context. `rules.py` is unchanged.",
        "",
        f"- historical names: {len(refs)}",
        f"- base law ids: {len(base_ids)}",
        f"- revisions fetched (all candidates, none pinned): {payload['revisions_fetched_total']}",
        f"- pinned: 0",
        "",
        "| historical name | occ | base law id | revisions | status |",
        "|---|---|---|---|---|",
    ]
    for c in candidates[:80]:
        lines.append(f"| {c['historical_name']} | {c['occurrences']} | {c['base_law_id']} | "
                     f"{c['revision_count']} | {c['pin_status']} |")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"candidates {len(candidates)} / pinned 0 / revisions {payload['revisions_fetched_total']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
