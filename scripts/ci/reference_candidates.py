#!/usr/bin/env python3
"""Reviewable, UNVERIFIED law-name -> law-id candidate layer (Directive §5).

This layer is strictly additive. It never auto-binds a reference: the
conservative classifier in scripts/law_audit/rules.py is unchanged, and every
candidate is `UNVERIFIED` with `LEGAL_REVIEW_PENDING`. Only exact normalized
name equality (NFKC + whitespace removal) is proposed; abbreviations, 新/旧
variants and partial names are deliberately left unresolved.
"""
from __future__ import annotations

import json
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
OUT = REPO / "data" / "REFERENCE_NAME_CANDIDATES.json"
DOC = REPO / "docs" / "REFERENCE_NAME_CANDIDATES.md"
RESOLVED = REPO / "data" / "RECURSIVE_DISCOVERY_RESOLVED.json"
DISCOVERED = REPO / "data" / "DISCOVERED_INVENTORY.json"
INVENTORY = REPO / "data" / "INVENTORY.json"
HISTORICAL = REPO / "data" / "HISTORICAL_PIN_CANDIDATES.json"


def norm(name: str) -> str:
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", str(name)))


def finding(code: str, H: str, T: str, D: str, C: str, U: str) -> dict:
    return {"code": code, "H": H, "T": T, "D": D, "C": C, "U": U}


def build() -> dict:
    resolved = json.loads(RESOLVED.read_text(encoding="utf-8"))
    discovered = json.loads(DISCOVERED.read_text(encoding="utf-8"))
    inv = json.loads(INVENTORY.read_text(encoding="utf-8"))
    hist = json.loads(HISTORICAL.read_text(encoding="utf-8"))

    titles: dict[str, set[str]] = {}
    for law in inv.get("laws", []):
        if law.get("law_id") and law.get("law_title"):
            titles.setdefault(norm(law["law_title"]), set()).add(law["law_id"])
    for law in discovered.get("laws", {}).values():
        for key in ("official_title", "discovered_name"):
            if law.get("law_id") and law.get(key):
                titles.setdefault(norm(law[key]), set()).add(law["law_id"])

    candidates = []
    for rec in resolved.get("unresolved", []):
        name = rec.get("name", "")
        ids = sorted(titles.get(norm(name), set()))
        if not ids or len(ids) != 1:  # ambiguity is never a candidate
            continue
        candidates.append({
            "name": name,
            "occurrences": rec.get("occurrences", 0),
            "candidate_law_id": ids[0],
            "basis": "EXACT_NORMALIZED_TITLE_EQUALITY",
            "status": "UNVERIFIED",
            "legal_review": "LEGAL_REVIEW_PENDING",
            "binding": "NOT_BOUND",
        })

    historical = []
    for cand in hist.get("candidates", []):
        historical.append({
            "name": cand.get("historical_name", cand.get("name", "")),
            "base_law_id": cand.get("base_law_id", ""),
            "occurrences": cand.get("occurrences", 0),
            "status": "PIN_REQUIRED_UNVERIFIED",
            "legal_review": "LEGAL_REVIEW_PENDING",
            "binding": "NOT_PINNED",
        })

    return {
        "tool": "scripts/ci/reference_candidates.py",
        "schema": 1,
        "rule": "exact normalized title equality only; never auto-bind; 新/旧 needs human review",
        "unresolved_names_total": resolved.get("unresolved_names", 0),
        "candidates_total": len(candidates),
        "candidates": sorted(candidates, key=lambda r: (-r["occurrences"], r["name"])),
        "historical_total": len(historical),
        "historical": historical,
        "findings": [
            finding("R1", "unbound references are silently dropped",
                    "exact-normalized title candidates only, recorded UNVERIFIED",
                    "ENFORCED", "exact equality may still be a wrong law in context",
                    "no human legal review is recorded; candidates are never bindings"),
            finding("R2", "新/旧 historical names could be auto-pinned to a modern law",
                    "separate PIN_REQUIRED_UNVERIFIED layer, never auto-pinned",
                    "ENFORCED", "historical enforcement context is not machine-decidable",
                    "all 91 historical names remain pending human review"),
        ],
    }


DOC_TEMPLATE = """# Reviewable UNVERIFIED law-name candidates (Directive §5)

Generated by `scripts/ci/reference_candidates.py`. **No candidate is bound.**
`rules.py` is unchanged; this layer only proposes exact normalized title
matches for human review. Human legal review is `LEGAL_REVIEW_PENDING` for
every row; no approval record is created.

- unresolved reference names: {unresolved}
- exact-title candidates (UNVERIFIED, NOT_BOUND): {candidates}
- historical names (PIN_REQUIRED_UNVERIFIED, NOT_PINNED): {historical}

| name | occurrences | candidate law id | status |
|---|---:|---|---|
{rows}
"""


def main() -> int:
    payload = build()
    data_text = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    write_data = not OUT.exists() or OUT.read_text(encoding="utf-8") != data_text
    if write_data:
        OUT.write_text(data_text, encoding="utf-8")
        print("wrote", OUT)
    rows = "\n".join(
        f"| {r['name']} | {r['occurrences']} | `{r['candidate_law_id']}` | {r['status']} |"
        for r in payload["candidates"]
    )
    doc_text = DOC_TEMPLATE.format(
        unresolved=payload["unresolved_names_total"],
        candidates=payload["candidates_total"],
        historical=payload["historical_total"],
        rows=rows,
    )
    if not DOC.exists() or DOC.read_text(encoding="utf-8") != doc_text:
        DOC.write_text(doc_text, encoding="utf-8")
        print("wrote", DOC)
    print(f"unresolved names {payload['unresolved_names_total']}; "
          f"exact-title UNVERIFIED candidates {payload['candidates_total']}; "
          f"historical UNVERIFIED {payload['historical_total']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
